-- database/schema.sql
-- Initial schema for OmniGraph OSINT local prototype
-- All identifiers use snake_case.

CREATE EXTENSION IF NOT EXISTS "uuid-ossp"; -- for UUID generation

-- Cases table
CREATE TABLE cases (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    title TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    is_closed BOOLEAN DEFAULT FALSE
);

-- Evidence files metadata (actual files stored on local FS)
CREATE TABLE evidence_files (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    case_id UUID NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    file_path TEXT NOT NULL,
    sha256 TEXT NOT NULL,
    mime_type TEXT,
    size_bytes BIGINT,
    uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    processing_status TEXT DEFAULT 'pending',
    processing_error TEXT
);

-- Entities extracted from evidence
CREATE TABLE entities (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    case_id UUID NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    type TEXT NOT NULL,
    name TEXT NOT NULL,
    confidence NUMERIC(3,2) NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Aliases for entities (different spellings, nicknames)
CREATE TABLE aliases (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    entity_id UUID NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    confidence NUMERIC(3,2) NOT NULL CHECK (confidence >= 0 AND confidence <= 1)
);

-- Relationships between entities
CREATE TABLE relationships (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    case_id UUID NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    source_entity_id UUID NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    target_entity_id UUID NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    type TEXT NOT NULL,
    confidence NUMERIC(3,2) NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
    evidence_id UUID REFERENCES evidence_files(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Transactions (financial flows)
CREATE TABLE transactions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    case_id UUID NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    sender_entity_id UUID NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    receiver_entity_id UUID NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    amount NUMERIC(12,2) NOT NULL,
    currency TEXT NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    evidence_id UUID REFERENCES evidence_files(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Extraction result storage (raw text, entities, relationships per evidence)
CREATE TABLE extraction_results (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    evidence_id UUID NOT NULL REFERENCES evidence_files(id) ON DELETE CASCADE,
    raw_text TEXT,
    json_result JSONB,
    extracted_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Alerts generated by analysis engine
CREATE TABLE alerts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    case_id UUID NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    type TEXT NOT NULL,
    severity TEXT NOT NULL,
    description TEXT NOT NULL,
    related_entity_ids UUID[],
    related_transaction_ids UUID[],
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    acknowledged BOOLEAN DEFAULT FALSE,
    acknowledgement_note TEXT
);

-- Indexes for fast lookup
CREATE INDEX idx_entities_case ON entities(case_id);
CREATE INDEX idx_evidence_case ON evidence_files(case_id);
CREATE INDEX idx_relationships_case ON relationships(case_id);
CREATE INDEX idx_transactions_case ON transactions(case_id);
CREATE INDEX idx_alerts_case ON alerts(case_id);

-- Full‑text search on entity names and aliases
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX idx_entities_name_gin ON entities USING GIN (name gin_trgm_ops);
CREATE INDEX idx_aliases_name_gin ON aliases USING GIN (alias gin_trgm_ops);
